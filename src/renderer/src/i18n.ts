const dicts: Record<Language, Dict> = { 'zh-CN': zh, en }

export type T = (key: TKey, vars?: Record<string, string | number>) => string

export function makeT(lang: Language): T {
  const dict = dicts[lang] ?? zh
  return (key, vars) => {
    let s: string = dict[key] ?? zh[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
    return s
  }
}
