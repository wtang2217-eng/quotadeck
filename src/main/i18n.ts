export type MainKey = keyof typeof zh

export function tr(lang: Language, key: MainKey, vars: Record<string, string | number> = {}): string {
  const table = lang === 'zh-CN' ? zh : en
  return table[key].replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`))
}

export function windowName(lang: Language, kind: LimitKind | 'fh' | 'sd'): string {
  const k = kind === 'fh' ? 'session' : kind === 'sd' ? 'weekly' : kind
  return tr(lang, `window.${k}` as MainKey)
}
